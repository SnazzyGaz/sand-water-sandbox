import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
const browser=await chromium.launch({executablePath:process.env.CHROME_PATH||(existsSync('/usr/bin/google-chrome')?'/usr/bin/google-chrome':undefined),headless:true,args:['--no-sandbox','--enable-unsafe-swiftshader','--use-gl=angle','--use-angle=swiftshader']});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
await page.goto(process.env.BASE_URL||'http://localhost:5173/');
await page.waitForFunction(()=>window.sandboxDiagnostics?.ready,{timeout:30000});
await page.waitForTimeout(2200);
console.log('initial',await page.evaluate(()=>window.sandboxDiagnostics));
await page.click('#pause');await page.waitForFunction(()=>window.sandboxDiagnostics.paused);
console.log('paused',await page.evaluate(()=>window.sandboxDiagnostics));const frozen=await page.evaluate(()=>window.sandboxDiagnostics.time);await page.waitForTimeout(300);assert.equal(await page.evaluate(()=>window.sandboxDiagnostics.time),frozen);
await page.click('[data-mode="water"]');
await page.mouse.move(820,500);await page.mouse.down();await page.waitForTimeout(700);await page.mouse.up();
console.log('probe after pour',await page.locator('#probe-values').textContent());
const before=await page.evaluate(()=>window.sandboxDiagnostics.added);await page.click('#flood');await page.waitForFunction(x=>window.sandboxDiagnostics.added>x+44,before);
console.log('poured',await page.evaluate(()=>window.sandboxDiagnostics));
await page.click('#view');await page.selectOption('#view','1');
await page.click('#pause');await page.waitForFunction(()=>!window.sandboxDiagnostics.paused);await page.waitForTimeout(1500);
await page.keyboard.press('1');await page.waitForFunction(()=>window.sandboxDiagnostics.mode==='raise');await page.mouse.move(900,600);await page.mouse.down();await page.waitForTimeout(700);await page.mouse.up();
await page.mouse.move(800,500);await page.mouse.down({button:'right'});await page.mouse.move(1000,550,{steps:10});await page.mouse.up({button:'right'});
await page.mouse.wheel(0,-200);await page.waitForTimeout(400);
console.log('final',await page.evaluate(()=>window.sandboxDiagnostics));console.log('errors',errors);
assert.equal(errors.length,0,errors.join('\n'));await browser.close();
